func TestSaveInputsSection(t *testing.T) {
	dir := t.TempDir()

	m := GetDefaultMeta(filepath.Join(dir, "meta.yaml"))
	m.SetInputs(Inputs{
		{
			Channel: "onlineconf.path",
			Provenance: Provenance{
				SourceKind:   SourceKindGit,
				SourceRepo:   "ssh://git@github.com/org/contracts.git",
				SourcePath:   "oc/keys.yaml",
				Ref:          "release/2026.10",
				Commit:       "0123456789abcdef",
				SourceSHA256: "aaaa",
			},
		},
		{
			Channel:    "metrics.path",
			Provenance: Provenance{SourceKind: SourceKindLocal, SourcePath: "./metrics-map.yaml", SourceSHA256: "bbbb"},
		},
	})
	m.SetManifest(Manifest{{Path: "a.go", Kind: KindGenerated, Hash: "aaa"}})

	if err := m.Save(); err != nil {
		t.Fatal(err)
	}

	data, err := os.ReadFile(filepath.Join(dir, "meta.yaml"))
	if err != nil {
		t.Fatal(err)
	}

	// Inputs come before the manifest (a handful of records against hundreds),
	// sorted by channel, one record per line like every manifest record.
	want := "version: 6\n" +
		"inputs:\n" +
		"    - {channel: metrics.path, source_kind: local, source_path: ./metrics-map.yaml, source_sha256: bbbb}\n" +
		"    - {channel: onlineconf.path, source_kind: git, " +
		"source_repo: 'ssh://git@github.com/org/contracts.git', source_path: oc/keys.yaml, " +
		"ref: release/2026.10, commit: 0123456789abcdef, source_sha256: aaaa}\n" +
		"manifest:\n" +
		"    - {path: a.go, kind: generated, hash: aaa}\n"

	if string(data) != want {
		t.Errorf("meta.yaml =\n%s\nwant\n%s", data, want)
	}
}

func TestInputsRoundTrip(t *testing.T) {
	rec := InputRecord{
		Channel: "workers.ingest.path",
		Provenance: Provenance{
			SourceKind:   SourceKindHTTP,
			SourceRepo:   "https://specs.example.com",
			SourcePath:   "/queues.yaml",
			SourceSHA256: "cccc",
		},
	}

	data, err := yaml.Marshal(Inputs{rec})
	if err != nil {
		t.Fatal(err)
	}

	if strings.Count(string(data), "\n") != 1 {
		t.Errorf("record must stay on a single line, got:\n%s", data)
	}

	var back Inputs
	if err := yaml.Unmarshal(data, &back); err != nil {
		t.Fatalf("unmarshal %s: %v", data, err)
	}

	if len(back) != 1 || back[0] != rec {
		t.Errorf("round trip = %+v, want %+v", back, rec)
	}
}

// One channel may resolve the same source twice in a run (two workers pointing
// at one contract): the section states facts, not counts.
func TestInputsNormalizeDeduplicates(t *testing.T) {
	rec := InputRecord{
		Channel:    "metrics.path",
		Provenance: Provenance{SourceKind: SourceKindLocal, SourcePath: "./map.yaml"},
	}

	other := InputRecord{
		Channel:    "metrics.path",
		Provenance: Provenance{SourceKind: SourceKindLocal, SourcePath: "./other.yaml"},
	}

	got := Inputs{other, rec, rec}.Normalize()

	if len(got) != 2 {
		t.Fatalf("normalized = %+v, want 2 records", got)
	}

	// Same channel: sorted by the source, so the file is stable between runs.
	if got[0].SourcePath != "./map.yaml" || got[1].SourcePath != "./other.yaml" {
		t.Errorf("normalized = %+v, want records sorted by source", got)
	}
}

// A newer schema is refused instead of partially understood: generation
// decides what to overwrite and what is a hand-written file by reading this
// manifest, and it cannot make those calls on records whose fields it does not
// know.
func TestGetMetaRefusesFutureVersion(t *testing.T) {
	dir := t.TempDir()

	body := []byte("version: 99\nmanifest:\n    - {path: a.go, kind: generated, hash: aaa}\n")
	if err := os.WriteFile(filepath.Join(dir, FileName), body, 0o600); err != nil {
		t.Fatal(err)
	}

	_, err := GetMeta(dir, FileName)
	if !errors.Is(err, ErrFutureVersion) {
		t.Fatalf("GetMeta() error = %v, want ErrFutureVersion", err)
	}

	if !strings.Contains(err.Error(), "version 99") {
		t.Errorf("error should name the version found, got %v", err)
	}
}

// A project generated by an older generator is read as before: the version is
// lower, and the run that follows rewrites it with the current one.
func TestGetMetaAcceptsOlderVersion(t *testing.T) {
	dir := t.TempDir()

	body := []byte("version: 5\nmanifest:\n    - {path: a.go, kind: generated, hash: aaa}\n")
	if err := os.WriteFile(filepath.Join(dir, FileName), body, 0o600); err != nil {
		t.Fatal(err)
	}

	m, err := GetMeta(dir, FileName)
	if err != nil {
		t.Fatalf("GetMeta() error = %v", err)
	}

	if len(m.Manifest) != 1 || m.Manifest[0].Path != "a.go" {
		t.Errorf("manifest = %+v, want the records of the older run", m.Manifest)
	}
}

// The provenance fields of the previous format (a single `source` string) are
// simply absent after the upgrade; a v5 record still parses, so the run that
// reads it can go on and rewrite the file with the current fields.
func TestGetMetaReadsLegacyRecord(t *testing.T) {
	dir := t.TempDir()

	body := []byte("version: 5\nmanifest:\n" +
		"    - {path: api/contract/limits.yaml, kind: copied, hash: ccc, source: ./limits.yaml, ref: main}\n")
	if err := os.WriteFile(filepath.Join(dir, FileName), body, 0o600); err != nil {
		t.Fatal(err)
	}

	m, err := GetMeta(dir, FileName)
	if err != nil {
		t.Fatalf("GetMeta() error = %v", err)
	}

	if len(m.Manifest) != 1 {
		t.Fatalf("manifest = %+v, want one record", m.Manifest)
	}

	// The hash is what every check compares against, and it is unchanged by
	// the format bump: a v5 tree is not reported as drifted after the upgrade.
	if m.Manifest[0].Hash != "ccc" {
		t.Errorf("hash = %q, want the recorded one", m.Manifest[0].Hash)
	}
}
